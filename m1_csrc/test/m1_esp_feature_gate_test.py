#!/usr/bin/env python3
"""Host tests for the ESP32 feature gate (PR-10 of the Merge 3 series,
PLAN section 13).

Same technique as m1_crypto_test.py: compile the REAL sources with a
generated harness (no mocks of the code under test) and, separately,
pin the wiring seams statically in the actual files.

Layers:

1. Compiled gate core (m1_csrc/m1_esp_feature_gate.c built with
   -DM1_ESP_GATE_HOST_TEST so the two console-touching operations are
   harness-provided and simulatable) linked with the REAL persisted-
   version record (m1_csrc/m1_esp_version.c built with
   -DM1CP_HOST_TEST: RAM-backed, m1cp_esp_version_set() seeds it and
   m1cp_esp_version_init() clears it -- exactly the VBAT-loss
   semantics of the backup-domain record on target):
   - version compare: field dominance in all four positions, rc as a
     plain fourth number (0.8.11 > 0.8.4, rc 0 vs 1), 0/255 bounds,
     equality, antisymmetry, NULL arguments;
   - reply parsing: clean marker line, marker amid console noise and
     the echoed command, tab separator, first-valid-wins over a
     garbled earlier marker, embedded occurrence ("ESPFWESPFW ..."),
     trailing text after the fourth field tolerated, and the
     negatives (missing field, non-numeric field, 256, 1000, 3-digit
     cap, lowercase marker, no marker at all, NULL);
   - minimum table: join {1,1,0,0} (PR-11 pairing), advertise
     {1,0,0,0}, unknown feature refused;
   - THE query matrix (live console simulated, cache controlled):
       console dead            -> ABSENT / NO_CONSOLE / refused
       version round trip fail -> ABSENT / TRANSPORT / refused
       alive, no marker        -> ABSENT / NO_VERSION / refused
       live < minimum          -> OLDER  / refused
       live == minimum         -> EQUIVALENT / allowed
       live > minimum          -> NEWER / allowed
     plus the stale-cache battery (the DR2/DR3 record must never
     gate):
       cache says {9,9,9,9}, console dead      -> still ABSENT
       cache says {9,9,9,9}, reply no marker   -> still ABSENT
       cache says {2,0,0,0}, live {0,9,9,9}    -> OLDER (live wins),
                                                   cache_disagrees
       cache cleared (VBAT loss), live current -> EQUIVALENT
     and the diagnostics/allow-policy contracts per state, the NULL
     detail path, and the bad-feature guard.

2. Static layer on the real sources:
   - m1_esp_feature_gate.c is in M1_APP_SOURCES (scoped -Werror);
   - the target seam rides the shipped ESP32 UART console session
     (esp32_uart_write + esp32_uart_read_complete_prompt with the
     ">> " prompt) and touches no UART/HAL handle directly;
   - the console transport include sits in the target branch only
     (host branch stays HAL/FreeRTOS-free);
   - the gate NEVER writes the persisted record (no
     m1cp_esp_version_set anywhere in the module);
   - the console verb and reply marker are pinned in the header
     (shared contract with the external ESP32 firmware);
   - m1_esp_version.c still owns DR2/DR3 exactly as before (this
     unit must not change backup-register ownership);
   - scripts/run_host_tests.sh runs this suite.

Usage: python3 m1_csrc/test/m1_esp_feature_gate_test.py
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

PASSED = 0
FAILED = 0


def CHECK(cond, msg):
    global PASSED, FAILED
    if cond:
        PASSED += 1
    else:
        FAILED += 1
        print(f"  FAIL: {msg}")


def source(path):
    return (ROOT / path).read_text()


def host_cc():
    for cc in ("cc", "gcc", "clang"):
        try:
            subprocess.run([cc, "--version"], capture_output=True, check=True)
            return cc
        except (FileNotFoundError, subprocess.CalledProcessError):
            continue
    raise AssertionError("no usable host C compiler (cc/gcc/clang) found")


# ---------------------------------------------------------------------------
# Compiled harness: gate core + real version record, simulated console
# ---------------------------------------------------------------------------

GATE_HARNESS = r"""
/* Generated by m1_csrc/test/m1_esp_feature_gate_test.py -- do not edit. */
#include <stdio.h>
#include <string.h>
#include <stdint.h>
#include <stdbool.h>
#include "m1_esp_feature_gate.h"
#include "m1_esp_version.h"

static int fails = 0;

#define FAILF(...) do { fails++; printf("  FAIL: " __VA_ARGS__); printf("\n"); } while (0)
#define CHECKN(c, m) do { if (!(c)) FAILF("%s", m); } while (0)

/* ---- console simulation (the two seam operations) ---- */
static bool sim_ping_ok;
static bool sim_version_ok;       /* false: version round trip fails */
static char sim_reply[256];       /* reply text returned for `version` */
static int  ping_calls;
static int  version_calls;

bool esp_gate_console_ping_seam(uint32_t timeout_ms)
{
    (void)timeout_ms;
    ping_calls++;
    return sim_ping_ok;
}

bool esp_gate_console_version_reply_seam(char *buf, uint16_t buf_size,
                                         uint32_t timeout_ms)
{
    (void)timeout_ms;
    version_calls++;
    if (!sim_version_ok) { return false; }
    if (buf_size == 0u)  { return false; }
    strncpy(buf, sim_reply, buf_size - 1u);
    buf[buf_size - 1u] = '\0';
    return true;
}

static void sim_reset(bool ping_ok, bool version_ok, const char *reply)
{
    sim_ping_ok = ping_ok;
    sim_version_ok = version_ok;
    memset(sim_reply, 0, sizeof(sim_reply));
    if (reply != NULL) { strncpy(sim_reply, reply, sizeof(sim_reply) - 1u); }
    ping_calls = 0;
    version_calls = 0;
}

/* Compare helper: expect a specific relation with full detail. */
static void expect_state(const char *name, esp_feature_t f,
                         esp_fw_state_t want_state,
                         esp_gate_absent_reason_t want_reason,
                         bool want_live, const uint8_t *want_live_ver,
                         bool want_cache_disagrees, bool want_allows,
                         const char *want_diag)
{
    esp_feature_gate_result_t r;
    esp_fw_state_t s;

    memset(&r, 0xAA, sizeof(r));
    s = esp_feature_gate_query(f, &r);

    if (s != want_state)
        FAILF("%s: state %d want %d", name, (int)s, (int)want_state);
    if (want_reason != ESP_GATE_REASON__COUNT /*sentinel: skip*/ &&
        r.reason != want_reason)
        FAILF("%s: reason %d want %d", name, (int)r.reason, (int)want_reason);
    if (r.state != s)
        FAILF("%s: detail state %d != return %d", name, (int)r.state, (int)s);
    if (r.live_valid != want_live)
        FAILF("%s: live_valid %d want %d", name, (int)r.live_valid, (int)want_live);
    if (want_live_ver != NULL &&
        memcmp(r.live_version, want_live_ver, 4u) != 0)
        FAILF("%s: live %u.%u.%u.%u want %u.%u.%u.%u", name,
              r.live_version[0], r.live_version[1], r.live_version[2],
              r.live_version[3], want_live_ver[0], want_live_ver[1],
              want_live_ver[2], want_live_ver[3]);
    if (r.cache_disagrees != want_cache_disagrees)
        FAILF("%s: cache_disagrees %d want %d", name,
              (int)r.cache_disagrees, (int)want_cache_disagrees);
    if (esp_feature_gate_allows(s) != want_allows)
        FAILF("%s: allows %d want %d", name,
              (int)esp_feature_gate_allows(s), (int)want_allows);
    if (strcmp(esp_feature_gate_diag(&r), want_diag) != 0)
        FAILF("%s: diag \"%s\" want \"%s\"", name,
              esp_feature_gate_diag(&r), want_diag);
}

#define RS ESP_GATE_REASON__COUNT   /* sentinel: don't check reason */
#define NL NULL                     /* don't check live version bytes */

static void test_compare(void)
{
    const uint8_t v084[] = {0, 8, 4, 9};
    const uint8_t v0811[] = {0, 8, 11, 0};
    const uint8_t v1234[] = {1, 2, 3, 4};
    const uint8_t v1235[] = {1, 2, 3, 5};

    CHECKN(esp_fw_version_compare(v1234, v1234) == 0, "compare equal");
    CHECKN(esp_fw_version_compare(v0811, v084) > 0, "minor 11 > 4 (not text order)");
    CHECKN(esp_fw_version_compare(v084, v0811) < 0, "compare antisymmetry");
    CHECKN(esp_fw_version_compare(v1234, v1235) < 0, "rc field orders");
    CHECKN(esp_fw_version_compare(v1235, v1234) > 0, "rc field orders (rev)");
    CHECKN(esp_fw_version_compare((const uint8_t[]){2,0,0,0}, v1235) > 0, "major dominates");
    CHECKN(esp_fw_version_compare((const uint8_t[]){1,3,0,0}, v1235) > 0, "minor dominates");
    CHECKN(esp_fw_version_compare((const uint8_t[]){1,2,4,0}, v1235) > 0, "patch dominates");
    CHECKN(esp_fw_version_compare((const uint8_t[]){0,0,0,0}, (const uint8_t[]){255,255,255,255}) < 0,
           "0 < 255 in every field");
    CHECKN(esp_fw_version_compare((const uint8_t[]){255,255,255,255}, (const uint8_t[]){0,0,0,0}) > 0,
           "255 > 0 (rev)");
    CHECKN(esp_fw_version_compare((const uint8_t[]){1,2,3,4}, (const uint8_t[]){1,2,3,255}) < 0,
           "rc 4 < 255");
    CHECKN(esp_fw_version_compare(NULL, v1234) == 0, "compare NULL a defensive");
    CHECKN(esp_fw_version_compare(v1234, NULL) == 0, "compare NULL b defensive");
    printf("compare done (%d fails so far)\n", fails);
}

static void test_parse(void)
{
    uint8_t v[4];

    CHECKN(esp_fw_parse_version_reply("ESPFW 1.2.3.4", v) &&
           v[0] == 1 && v[1] == 2 && v[2] == 3 && v[3] == 4, "clean marker");
    CHECKN(esp_fw_parse_version_reply("version\r\nESPFW 1.2.3.4\r\n>> ", v),
           "echoed command + prompt around marker");
    CHECKN(esp_fw_parse_version_reply(
               "some console banner\r\nESPFW 10.20.30.40 rc\r\n>> ", v) &&
           v[0] == 10 && v[1] == 20 && v[2] == 30 && v[3] == 40,
           "noise lines + suffix after 4th field");
    CHECKN(esp_fw_parse_version_reply("ESPFW\t9.0.1\r\n>> ", v) == false,
           "missing 4th field");
    CHECKN(esp_fw_parse_version_reply("ESPFW 0.9.1.3", v) &&
           v[0] == 0 && v[1] == 9 && v[2] == 1 && v[3] == 3, "zeros parse");
    CHECKN(esp_fw_parse_version_reply("ESPFW 1.2.X.4", v) == false,
           "non-numeric field");
    CHECKN(esp_fw_parse_version_reply("ESPFW 256.1.1.1", v) == false,
           "256 out of range");
    CHECKN(esp_fw_parse_version_reply("ESPFW 1000.1.1.1", v) == false,
           "1000 out of range");
    CHECKN(esp_fw_parse_version_reply("ESPFW 1.2.3.4.5", v) &&
           v[3] == 4, "trailing 5th field tolerated after 4 valid");
    CHECKN(esp_fw_parse_version_reply("ESPFWESPFW 5.6.7.8", v) &&
           v[0] == 5 && v[1] == 6 && v[2] == 7 && v[3] == 8,
           "garbled first occurrence, embedded second parses");
    CHECKN(esp_fw_parse_version_reply("ESPFWX 1.2.3.4 ESPFW 2.0.0.0", v) &&
           v[0] == 2, "first marker mangled, later valid wins");
    CHECKN(esp_fw_parse_version_reply("ESPFW  1.2.3.4", v),
           "multiple spaces after marker");
    CHECKN(esp_fw_parse_version_reply("espfw 1.2.3.4", v) == false,
           "marker is case-sensitive");
    CHECKN(esp_fw_parse_version_reply("", v) == false, "empty reply");
    CHECKN(esp_fw_parse_version_reply(">> ", v) == false, "prompt only");
    CHECKN(esp_fw_parse_version_reply("unknown command\r\n>> ", v) == false,
           "no marker in reply");
    CHECKN(esp_fw_parse_version_reply(NULL, v) == false, "NULL reply");
    CHECKN(esp_fw_parse_version_reply("ESPFW 1.2.3.4", NULL) == false,
           "NULL out");
    printf("parse done (%d fails so far)\n", fails);
}

static void test_minimums(void)
{
    uint8_t m[4];

    CHECKN(esp_feature_minimum(ESP_FEATURE_WIFI_JOIN, m) &&
           m[0] == 1 && m[1] == 1 && m[2] == 0 && m[3] == 0,
           "wifi join minimum {1,1,0,0} (PR-11 pairing)");
    CHECKN(esp_feature_minimum(ESP_FEATURE_BLE_ADVERTISE, m) &&
           m[0] == 1 && m[1] == 0 && m[2] == 0 && m[3] == 0,
           "ble advertise minimum {1,0,0,0}");
    CHECKN(esp_feature_minimum((esp_feature_t)99, m) == false,
           "unknown feature refused");
    CHECKN(esp_feature_minimum(ESP_FEATURE_WIFI_JOIN, NULL) == false,
           "NULL out refused");
    printf("minimums done (%d fails so far)\n", fails);
}

static void test_query_matrix(void)
{
    const uint8_t min_v[] = {1, 1, 0, 0};
    const uint8_t older_v[] = {0, 9, 9, 9};
    const uint8_t newer_v[] = {1, 0, 1, 0};
    const uint8_t cache_new_v[] = {9, 9, 9, 9};
    const uint8_t cache_other_new_v[] = {2, 0, 0, 0};
    uint8_t m[4];

    /* 1. console dead -- even with a cache that says new firmware. */
    m1cp_esp_version_set(cache_new_v);
    sim_reset(false, true, "ESPFW 1.0.0.0\r\n>> ");
    expect_state("dead console", ESP_FEATURE_WIFI_JOIN, ESP_FW_ABSENT,
                 ESP_GATE_REASON_NO_CONSOLE, false, NL, false, false,
                 "ESP not responding");
    CHECKN(version_calls == 0, "dead console: version round trip not attempted");

    /* 2. console alive, version round trip fails after ping. */
    sim_reset(true, false, "");
    expect_state("transport fail", ESP_FEATURE_WIFI_JOIN, ESP_FW_ABSENT,
                 ESP_GATE_REASON_TRANSPORT, false, NL, false, false,
                 "ESP link failed");

    /* 3. console alive, reply carries no version -- cache still says new. */
    sim_reset(true, true, "unknown command\r\n>> ");
    expect_state("no marker", ESP_FEATURE_WIFI_JOIN, ESP_FW_ABSENT,
                 ESP_GATE_REASON_NO_VERSION, false, NL, false, false,
                 "ESP fw unknown");

    /* 3b. live firmware BELOW the join minimum (e.g. a 1.0.0.0 image,
     * which the pre-PR-11 placeholder accepted): OLDER, refused (the
     * case-1 cache of {9,9,9,9} is still loaded -- disagreeing, never
     * gating). */
    sim_reset(true, true, "ESPFW 1.0.0.0\r\n>> ");
    expect_state("join minimum gates 1.0.0.0", ESP_FEATURE_WIFI_JOIN,
                 ESP_FW_OLDER, RS, true, (const uint8_t[]){1, 0, 0, 0},
                 true, false, "ESP update required");

    /* 4. live == minimum. */
    m1cp_esp_version_set(min_v);
    sim_reset(true, true, "ESPFW 1.1.0.0\r\n>> ");
    expect_state("equivalent", ESP_FEATURE_WIFI_JOIN, ESP_FW_EQUIVALENT,
                 RS, true, min_v, false, true, "ESP fw supported");

    /* 5. live > minimum. */
    sim_reset(true, true, "ESPFW 1.0.1.0\r\n>> ");
    expect_state("newer", ESP_FEATURE_BLE_ADVERTISE, ESP_FW_NEWER,
                 RS, true, newer_v, true, true, "ESP fw newer");

    /* 6. live < minimum. */
    sim_reset(true, true, "ESPFW 0.9.9.9\r\n>> ");
    expect_state("older", ESP_FEATURE_WIFI_JOIN, ESP_FW_OLDER,
                 RS, true, older_v, true, false, "ESP update required");

    /* 7. STALE CACHE, the core scenario: the DR2/DR3 record says
     * {2,0,0,0} (a newer firmware was once installed) but the live
     * console reports {0,9,9,9} -- the gate must follow the LIVE
     * answer and refuse. */
    m1cp_esp_version_set(cache_other_new_v);
    sim_reset(true, true, "ESPFW 0.9.9.9\r\n>> ");
    {
        esp_feature_gate_result_t r;
        esp_fw_state_t s = esp_feature_gate_query(ESP_FEATURE_WIFI_JOIN, &r);
        CHECKN(s == ESP_FW_OLDER, "stale cache: live older gates");
        CHECKN(!esp_feature_gate_allows(s), "stale cache: refused");
        CHECKN(r.cache_valid, "stale cache: record readable");
        CHECKN(r.cache_disagrees, "stale cache: disagreement surfaced");
        CHECKN(esp_fw_version_compare(r.cache_version, cache_other_new_v) == 0,
               "stale cache: record bytes reported");
    }

    /* 8. VBAT-loss direction: record cleared, live current -> allowed.
     * The live answer is authoritative in BOTH directions. */
    m1cp_esp_version_init();   /* host: clears to unavailable */
    sim_reset(true, true, "ESPFW 1.0.0.0\r\n>> ");
    {
        esp_feature_gate_result_t r;
        esp_fw_state_t s = esp_feature_gate_query(ESP_FEATURE_BLE_ADVERTISE, &r);
        CHECKN(s == ESP_FW_EQUIVALENT, "cleared cache: live still gates");
        CHECKN(esp_feature_gate_allows(s), "cleared cache: allowed");
        CHECKN(!r.cache_valid, "cleared cache: record unavailable");
        CHECKN(!r.cache_disagrees, "cleared cache: no disagreement claim");
    }

    /* 9. bad feature guard + NULL detail path. */
    sim_reset(true, true, "ESPFW 1.1.0.0\r\n>> ");
    expect_state("bad feature", (esp_feature_t)99, ESP_FW_ABSENT,
                 ESP_GATE_REASON_BAD_FEATURE, false, NL, false, false,
                 "ESP gate misuse");
    {
        esp_fw_state_t s = esp_feature_gate_query(ESP_FEATURE_WIFI_JOIN, NULL);
        CHECKN(s == ESP_FW_EQUIVALENT, "NULL detail still returns state");
    }

    /* 10. allows() policy over every state. */
    CHECKN(esp_feature_gate_allows(ESP_FW_ABSENT) == false, "allows ABSENT");
    CHECKN(esp_feature_gate_allows(ESP_FW_OLDER) == false, "allows OLDER");
    CHECKN(esp_feature_gate_allows(ESP_FW_EQUIVALENT) == true, "allows EQUIVALENT");
    CHECKN(esp_feature_gate_allows(ESP_FW_NEWER) == true, "allows NEWER");

    /* 11. diagnostics: never NULL, distinct per state, generic text
     * without detail. */
    CHECKN(esp_feature_gate_diag(NULL) != NULL, "diag(NULL) not NULL");
    CHECKN(strcmp(esp_feature_gate_diag(NULL), "ESP not responding") == 0,
           "diag(NULL) generic absent text");
    CHECKN(ping_calls > 0, "ping seam exercised");
    CHECKN(m != NULL, "dummy");
    printf("query matrix done (%d fails so far)\n", fails);
}

int main(void)
{
    test_compare();
    test_parse();
    test_minimums();
    test_query_matrix();

    if (fails == 0)
    {
        printf("ESP GATE OK\n");
        return 0;
    }
    printf("ESP GATE FAILED (%d)\n", fails);
    return 1;
}
"""


def compiled_layer(cc):
    import tempfile

    with tempfile.TemporaryDirectory() as td:
        tdir = Path(td)
        harness = tdir / "esp_gate_test.c"
        harness.write_text(GATE_HARNESS)
        exe = tdir / "esp_gate_test"
        cmd = [
            cc,
            "-std=c99",
            "-O2",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-pedantic",
            "-DM1_ESP_GATE_HOST_TEST",
            "-DM1CP_HOST_TEST",
            "-I",
            str(ROOT / "m1_csrc"),
            str(ROOT / "m1_csrc" / "m1_esp_feature_gate.c"),
            str(ROOT / "m1_csrc" / "m1_esp_version.c"),
            str(harness),
            "-o",
            str(exe),
        ]
        r = subprocess.run(cmd, capture_output=True, text=True)
        CHECK(
            r.returncode == 0,
            f"gate core compile failed: {r.stderr.strip()[:400]}",
        )
        if r.returncode != 0:
            return
        r = subprocess.run([str(exe)], capture_output=True, text=True)
        CHECK(
            r.returncode == 0 and "ESP GATE OK" in r.stdout,
            f"gate core run failed:\n{r.stdout}",
        )


# ---------------------------------------------------------------------------
# Static layer: wiring seams in the real sources
# ---------------------------------------------------------------------------


def static_checks():
    # 1. The gate is inside the scoped -Werror app-source list.
    cmake = source("cmake/m1_01/CMakeLists.txt")
    CHECK(
        "../../m1_csrc/m1_esp_feature_gate.c" in cmake,
        "m1_esp_feature_gate.c not in M1_APP_SOURCES (scoped -Werror gate)",
    )

    # 2. Target seam rides the shipped UART console transport and
    #    touches no UART/HAL handle directly.
    gate = source("m1_csrc/m1_esp_feature_gate.c")
    CHECK(
        "esp32_uart_write(" in gate,
        "gate does not send via esp32_uart_write (the shipped console transport)",
    )
    CHECK(
        "esp32_uart_read_complete_prompt(" in gate,
        "gate does not read via esp32_uart_read_complete_prompt",
    )
    CHECK(
        '">> "' in gate,
        'gate does not confirm the ">> " console prompt',
    )
    CHECK(
        "HAL_UART" not in gate and "huart_esp" not in gate,
        "gate touches UART/HAL handles directly (must go through the seam)",
    )

    # 3. The transport include lives in the target branch only (the
    #    host branch must stay HAL/FreeRTOS-free).
    host_branch = gate.split("#ifdef M1_ESP_GATE_HOST_TEST", 1)[1]
    target_branch = host_branch.split("#else", 1)[1].split("#endif", 1)[0]
    CHECK(
        '#include "m1_esp_uart_transport.h"' in target_branch
        and '#include "m1_esp_uart_transport.h"'
        not in host_branch.split("#else", 1)[0],
        "console transport include must be target-branch only",
    )

    # 4. The gate never writes the persisted record (diagnostics only).
    CHECK(
        "m1cp_esp_version_set" not in gate,
        "gate writes the DR2/DR3 record via m1cp_esp_version_set (must not)",
    )

    # 5. The console verb and reply marker are pinned (the contract
    #    shared with the external ESP32 console firmware).
    header = source("m1_csrc/m1_esp_feature_gate.h")
    CHECK(
        '#define ESP_GATE_VERSION_CMD       "version\\r\\n"' in header,
        "console verb pinned as version<CRLF>",
    )
    CHECK(
        '#define ESP_GATE_VERSION_MARKER    "ESPFW"' in header,
        "reply marker pinned as ESPFW",
    )

    # 6. Backup-register ownership untouched: the persisted record
    #    still owns DR2/DR3 exactly as before this unit.
    ver = source("m1_csrc/m1_esp_version.c")
    CHECK(
        "#define ESP_VER_REG        RTC_BKP_DR2" in ver
        and "#define ESP_VER_MAGIC_REG  RTC_BKP_DR3" in ver,
        "m1_esp_version.c DR2/DR3 ownership changed",
    )

    # 7. The aggregator runs this suite.
    runner = source("scripts/run_host_tests.sh")
    CHECK(
        "m1_csrc/test/m1_esp_feature_gate_test.py" in runner,
        "suite not wired into scripts/run_host_tests.sh",
    )


def main():
    cc = host_cc()
    compiled_layer(cc)
    static_checks()

    print(f"\n{PASSED} passed, {FAILED} failed")
    if FAILED:
        sys.exit(1)
    print("ALL ESP FEATURE GATE TESTS PASSED")


if __name__ == "__main__":
    main()
